// PR Resolver — the auto-fix stage.
//
// Mirrors the Qodo "PR Resolver" skill: take review findings, apply the
// known fixes, then re-verify. Only findings with a registered fix are
// touched; everything else stays open and escalates (AGENTS.md rule 5).
import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';

/**
 * Attempt to fix findings.
 * @param {string} root
 * @param {Array} findings
 * @param {object} ticket
 * @returns {{ fixed: Array, remaining: Array }}
 */
export function resolveFindings(root, findings, ticket) {
  const fixed = [];
  const remaining = [];
  for (const f of findings) {
    if (f.severity === 'info') continue; // not a problem
    if (f.type === 'missing-test') {
      const res = fixMissingTest(root, f, ticket);
      if (res) fixed.push({ ...f, fix: res });
      else remaining.push(f);
    } else {
      remaining.push(f); // no registered fix — escalate
    }
  }
  return { fixed, remaining };
}

/** Generate a smoke test for a changed module that has none. */
function fixMissingTest(root, finding, ticket) {
  const testFile = (ticket.tests && ticket.tests[0]) || null;
  const moduleFile = finding.file;
  if (!testFile || !moduleFile) return null;
  const testPath = join(root, testFile);
  if (existsSync(testPath)) return null; // already exists — nothing to fix
  const importPath = './' + relative(dirname(testPath), join(root, moduleFile)).replace(/\\/g, '/');
  const name = moduleFile.split('/').pop();
  const content = `// Auto-generated by the factory PR Resolver (missing-test fix).
import test from 'node:test';
import assert from 'node:assert/strict';

test('smoke: ${name} loads and exports', async () => {
  const mod = await import('${importPath}');
  assert.ok(mod && typeof mod === 'object', 'module should load');
});
`;
  mkdirSync(dirname(testPath), { recursive: true });
  writeFileSync(testPath, content);
  return `generated smoke test ${testFile}`;
}
