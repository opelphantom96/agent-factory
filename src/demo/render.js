// F1 telemetry dashboard generator — dependency-free HTML + inline SVG.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { generateLap } from './telemetry.js';
import { FEATURES } from './features.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_DIR = join(ROOT, 'apps', 'f1-telemetry');

const W = 920; const H = 220; const PAD = { l: 48, r: 12, t: 14, b: 28 };

function xFor(d, lapLengthM) {
  return PAD.l + (d / lapLengthM) * (W - PAD.l - PAD.r);
}

function yFor(v, max, height = H) {
  return PAD.t + (1 - v / max) * (height - PAD.t - PAD.b);
}

function pathFrom(samples, value, max, lapLengthM) {
  return samples
    .map((s, i) => `${i === 0 ? 'M' : 'L'}${xFor(s.distance, lapLengthM).toFixed(1)},${yFor(value(s), max).toFixed(1)}`)
    .join(' ');
}

function chart({ title, yLabel, yMax, yTicks, series, svgExtra = '' }) {
  const ticks = yTicks.map((t) => {
    const y = yFor(t, yMax);
    return `<line x1="${PAD.l}" y1="${y}" x2="${W - PAD.r}" y2="${y}" stroke="#e5e7eb"/>`
      + `<text x="${PAD.l - 6}" y="${y + 4}" text-anchor="end" font-size="11" fill="#6b7280">${t}</text>`;
  }).join('');
  const lines = series.map((s) => `<path d="${s.d}" fill="none" stroke="${s.color}" stroke-width="2"/>`).join('');
  const xTicks = [0, 1000, 2000, 3000, 4000, 5000].map((d) => {
    const x = xFor(d, 5412);
    return `<text x="${x}" y="${H - 8}" text-anchor="middle" font-size="11" fill="#6b7280">${d} m</text>`;
  }).join('');
  return `<section><h2>${title}</h2><svg width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="${title}">`
    + `<rect x="0" y="0" width="${W}" height="${H}" fill="#ffffff"/>${ticks}${svgExtra}${lines}${xTicks}`
    + `<text x="14" y="${PAD.t + 8}" font-size="11" fill="#6b7280" transform="rotate(-90 14 ${PAD.t + 8})" text-anchor="middle">${yLabel}</text>`
    + `</svg></section>`;
}

/** Build the full dashboard HTML for a lap. */
export function buildDashboard(lap = generateLap(42)) {
  const { samples, stats } = lap;
  const speedD = pathFrom(samples, (s) => s.speed, 350, lap.lapLengthM);
  const throttleD = pathFrom(samples, (s) => s.throttle, 100, lap.lapLengthM);
  const gearD = pathFrom(samples, (s) => s.gear, 8, lap.lapLengthM);

  let svgExtra = '';
  let htmlExtra = '';
  for (const f of FEATURES) {
    const out = f.render({
      samples, stats, lap,
      xFor: (d) => xFor(d, lap.lapLengthM),
      yForSpeed: (v) => yFor(v, 350),
    });
    if (out.svgExtra) svgExtra += out.svgExtra;
    if (out.htmlExtra) htmlExtra += out.htmlExtra;
  }

  const statsHtml = `
    <section class="stats">
      <div><span>Lap time</span><strong>${stats.lapTimeS.toFixed(3)} s</strong></div>
      <div><span>Top speed</span><strong>${stats.topSpeed} km/h</strong></div>
      <div><span>Avg speed</span><strong>${stats.avgSpeed} km/h</strong></div>
      <div><span>Full throttle</span><strong>${stats.fullThrottlePct}%</strong></div>
      <div><span>Braking</span><strong>${stats.brakingPct}%</strong></div>
    </section>`;

  return `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>F1 Telemetry — Harbour Ring, Lap 12</title>
<style>body{font-family:system-ui,sans-serif;max-width:960px;margin:0 auto;padding:24px;color:#111827}
h1{font-size:24px}h2{font-size:16px;margin:20px 0 8px}.stats{display:flex;gap:16px;flex-wrap:wrap;margin:16px 0}
.stats div{background:#f3f4f6;border-radius:8px;padding:12px 16px;min-width:120px}
.stats span{display:block;font-size:12px;color:#6b7280}.stats strong{font-size:20px}
section svg{border:1px solid #e5e7eb;border-radius:8px}table{border-collapse:collapse}
td,th{border:1px solid #d1d5db;padding:6px 10px;text-align:left;font-size:14px}
.legend{display:flex;gap:16px;flex-wrap:wrap}.legend span{font-size:14px}
.swatch{display:inline-block;width:14px;height:14px;border-radius:3px;margin-right:6px;vertical-align:-2px}
footer{color:#6b7280;font-size:13px;margin-top:24px}</style></head><body>
<h1>F1 Telemetry — Harbour Ring, Lap 12</h1>
<p>5,412 m lap · 542 samples · generated by the Agent Factory demo app.</p>
${statsHtml}
${chart({ title: 'Speed (km/h)', yLabel: 'km/h', yMax: 350, yTicks: [0, 100, 200, 300], series: [{ d: speedD, color: '#dc2626' }], svgExtra })}
${chart({ title: 'Throttle (%)', yLabel: '%', yMax: 100, yTicks: [0, 50, 100], series: [{ d: throttleD, color: '#16a34a' }] })}
${chart({ title: 'Gear', yLabel: 'gear', yMax: 8, yTicks: [1, 4, 8], series: [{ d: gearD, color: '#2563eb' }] })}
${htmlExtra}
<footer>Built by Agent Factory — Qodo Hackathon 2026. Features: ${FEATURES.map((f) => f.id).join(', ') || 'base only'}.</footer>
</body></html>`;
}

function main() {
  const lap = generateLap(42);
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, 'index.html'), buildDashboard(lap));
  writeFileSync(join(OUT_DIR, 'data.json'), JSON.stringify(lap, null, 2));
  console.log(`dashboard written: ${join(OUT_DIR, 'index.html')}`);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) main();
